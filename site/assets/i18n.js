export function makeT(lang) {
  const d = STRINGS[lang] || STRINGS.en;
  return (k, vars) => {
    let s = d[k] ?? STRINGS.en[k] ?? k;
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, v);
    return s;
  };
}
